"""Regenerate src/generated/papermono_selftest_epub.c.

The on-device content import self-test needs a real (if minimal) EPUB. The
fixture is a deterministic stored-ZIP EPUB so the generated bytes are stable.
"""

import io
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/generated/papermono_selftest_epub.c"


def build_epub():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_STORED) as z:
        z.writestr("mimetype", "application/epub+zip")
        z.writestr(
            "META-INF/container.xml",
            '<?xml version="1.0"?><container version="1.0" '
            'xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles>'
            '<rootfile full-path="OEBPS/content.opf" '
            'media-type="application/oebps-package+xml"/></rootfiles></container>')
        z.writestr(
            "OEBPS/content.opf",
            '<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" '
            'version="3.0" unique-identifier="id"><metadata '
            'xmlns:dc="http://purl.org/dc/elements/1.1/">'
            '<dc:identifier id="id">papermmono-selftest</dc:identifier>'
            '<dc:title>Selftest</dc:title><dc:language>zh</dc:language></metadata>'
            '<manifest><item id="c1" href="chapter1.xhtml" '
            'media-type="application/xhtml+xml"/></manifest>'
            '<spine><itemref idref="c1"/></spine></package>')
        z.writestr(
            "OEBPS/chapter1.xhtml",
            '<?xml version="1.0"?><html xmlns="http://www.w3.org/1999/xhtml">'
            '<head><title>c1</title></head><body><h1>自检</h1><p>EPUB 导入测试。</p>'
            '</body></html>')
    return buf.getvalue()


def render(data):
    lines = [
        "/*",
        " * Copyright (c) 2026 PaperMono Zephyr contributors",
        " *",
        " * SPDX-License-Identifier: GPL-3.0-only",
        " *",
        " * Minimal EPUB used by the on-device content import self-test. Generated by",
        " * scripts/generate_selftest_epub.py; do not edit by hand.",
        " */",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "const uint8_t papermono_selftest_epub[] = {",
    ]
    for start in range(0, len(data), 12):
        chunk = ", ".join(f"0x{byte:02x}" for byte in data[start:start + 12])
        lines.append(f"\t{chunk},")
    lines += ["};", "", f"const size_t papermono_selftest_epub_size = {len(data)}U;"]
    return "\n".join(lines) + "\n"


def main():
    OUTPUT.write_text(render(build_epub()))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()

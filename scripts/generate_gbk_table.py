#!/usr/bin/env python3
"""Generate the deterministic GBK double-byte to Unicode lookup table."""

from pathlib import Path


INVALID = 0xFFFF


def unicode_for_pair(lead: int, trail: int) -> int:
    """Return the BMP codepoint or INVALID (0xFFFF).

    The generated table stores uint16_t values, so 0xFFFF is reserved for
    invalid pairs and cannot collide with a supported mapping.
    """
    try:
        decoded = bytes((lead, trail)).decode("gbk")
    except UnicodeDecodeError:
        return INVALID
    if len(decoded) != 1:
        return INVALID
    value = ord(decoded)
    if value >= INVALID:
        return INVALID
    return value


def main() -> None:
    output = Path(__file__).resolve().parents[1] / "src" / "generated" / "papermono_gbk_table.c"
    values: list[int] = []
    for lead in range(0x81, 0xFF):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
            values.append(unicode_for_pair(lead, trail))

    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* Generated by scripts/generate_gbk_table.py; do not edit. */",
        "",
        "#include <stdint.h>",
        "",
        f"#define GBK_TABLE_LEAD_COUNT {0xFF - 0x81}U",
        "#define GBK_TABLE_TRAIL_COUNT 190U",
        "",
        f"static const uint16_t gbk_to_unicode[{len(values)}] = {{",
    ]
    for start in range(0, len(values), 12):
        chunk = ", ".join(f"0x{value:04X}" for value in values[start : start + 12])
        lines.append(f"\t{chunk},")
    lines.extend(
        [
            "};",
            "",
            "_Static_assert(GBK_TABLE_LEAD_COUNT * GBK_TABLE_TRAIL_COUNT ==",
            "\t\t   sizeof(gbk_to_unicode) / sizeof(gbk_to_unicode[0]),",
            "\t\"GBK table size mismatch\");",
            "",
            "uint16_t papermono_gbk_unicode(uint8_t lead, uint8_t trail)",
            "{",
            "\tuint16_t trail_index;",
            "",
            "\tif (lead < 0x81U || lead > 0xFEU || trail < 0x40U ||",
            "\t    trail == 0x7FU || trail > 0xFEU) {",
            f"\t\treturn {INVALID:#06x}U;",
            "\t}",
            "\ttrail_index = trail < 0x7FU ? trail - 0x40U : trail - 0x41U;",
            "\treturn gbk_to_unicode[(lead - 0x81U) * GBK_TABLE_TRAIL_COUNT +",
            "\t\t\t     trail_index];",
            "}",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()

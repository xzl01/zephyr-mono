#!/usr/bin/env python3
"""Convert one monochrome PNG into a transparent LVGL v9 I1 C image.

The PNG is an intermediate raster produced from a licensed vector asset.  The
checked-in C output keeps firmware builds independent of Pillow and Quick Look.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--name", required=True)
    parser.add_argument("--size", type=int, required=True)
    parser.add_argument("--threshold", type=int, default=168)
    return parser.parse_args()


def packed_bitmap(image: Image.Image, threshold: int) -> bytes:
    rgba = image.convert("RGBA")
    width, height = rgba.size
    if width % 8:
        raise ValueError("I1 image width must be divisible by eight")
    packed = bytearray()
    pixels = rgba.load()
    for y in range(height):
        for x0 in range(0, width, 8):
            value = 0
            for bit in range(8):
                red, green, blue, alpha = pixels[x0 + bit, y]
                luminance = (red * 299 + green * 587 + blue * 114) // 1000
                if alpha >= 64 and luminance < threshold:
                    value |= 1 << (7 - bit)
            packed.append(value)
    return bytes(packed)


def write_c(output: Path, name: str, size: int, bitmap: bytes) -> None:
    # Indexed palette is stored as BGRA.  Index zero is transparent paper;
    # index one is opaque ink.
    data = bytes((0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0xFF)) + bitmap
    rows = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        rows.append("    " + " ".join(f"0x{value:02x}," for value in chunk))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        """/* SPDX-License-Identifier: GPL-3.0-only */
/* Generated by scripts/generate_ui_asset.py from assets/phosphor/cat-fill.svg. */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST
uint8_t {name}_map[] = {{
{data}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_I1,
        .flags = 0,
        .w = {size},
        .h = {size},
        .stride = {stride},
        .reserved_2 = 0,
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
    .reserved = NULL,
}};
""".format(name=name, data="\n".join(rows), size=size, stride=size // 8),
        encoding="utf-8",
    )


def main() -> None:
    args = parse_args()
    source = Image.open(args.input).convert("RGBA")
    source.thumbnail((args.size - 4, args.size - 4), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (args.size, args.size), (255, 255, 255, 0))
    canvas.alpha_composite(
        source,
        ((args.size - source.width) // 2, (args.size - source.height) // 2),
    )
    write_c(
        args.output,
        args.name,
        args.size,
        packed_bitmap(canvas, args.threshold),
    )


if __name__ == "__main__":
    main()
